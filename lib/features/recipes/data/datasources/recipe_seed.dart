/// Örnek katalogdan hesaplanan başlangıç tarifleri.
///
/// Besin değerleri [SampleFoodCatalog] (USDA SR Legacy, yuvarlanmış demo
/// veri) üzerinden [RecipeNutritionCalculator] ile üretilir. Doğrulanmış
/// bir üretim veritabanı değildir; [Recipe.isDemo] ile işaretlenir.
abstract final class RecipeSeed {
  static final DateTime createdAt = DateTime.utc(2026, 1, 15);

  static final List<Recipe> recipes = _build();

  static Recipe? byId(String id) =>
      recipes.where((recipe) => recipe.id == id).firstOrNull;

  static List<Recipe> _build() {
    final byId = {
      for (final food in SampleFoodCatalog.foods) food.id: food,
      for (final food in SampleFoodCatalog.foods)
        if (food.id.startsWith('sample-')) food.id.substring(7): food,
    };
    final calculator = RecipeNutritionCalculator((id) => byId[id]);
    return [for (final spec in _specs) _recipe(spec, calculator)];
  }

  static Recipe _recipe(_Spec spec, RecipeNutritionCalculator calculator) {
    final built = calculator.build(servings: spec.servings, lines: spec.lines);
    final draft = Recipe(
      id: 'catalog-${spec.id}',
      title: spec.title,
      servings: spec.servings,
      nutritionPerServing: built.perServing,
      ingredients: built.ingredients,
      mealTypes: [spec.meal],
    );
    final nutrition = built.perServing;
    final tags = <String>{
      spec.meal.name,
      ...spec.extra,
      if (nutrition.proteinG >= RecipeCategory.highProteinGrams)
        RecipeTags.highProtein,
      if (nutrition.calories > 0 &&
          nutrition.calories <= RecipeCategory.lowCalorieKcal)
        RecipeTags.lowCalorie,
      if (spec.prep + spec.cook <= 20) ...[
        RecipeTags.quick,
        RecipeTags.practical,
      ],
      if ((nutrition.fiberG ?? 0) >= 6) RecipeTags.fiberRich,
      if (RecipeSuitability.matchesDiet(draft, DietType.vegetarian))
        RecipeTags.vegetarian,
      if (RecipeSuitability.matchesDiet(draft, DietType.vegan)) RecipeTags.vegan,
      if (spec.servings >= 2 || spec.extra.contains(RecipeTags.mealPrep))
        RecipeTags.mealPrep,
    };
    final category = spec.extra.contains(RecipeTags.soup)
        ? RecipeTags.soup
        : spec.extra.contains(RecipeTags.salad)
        ? RecipeTags.salad
        : spec.meal.name;
    return Recipe(
      id: draft.id,
      title: spec.title,
      description: spec.description,
      servings: spec.servings,
      prepMinutes: spec.prep,
      cookMinutes: spec.cook,
      nutritionPerServing: nutrition,
      ingredients: built.ingredients,
      steps: spec.steps,
      tags: tags.toList()..sort(),
      category: category,
      mealTypes: [spec.meal],
      source: RecipeSource.seed,
      createdAt: createdAt,
      updatedAt: createdAt,
      isDemo: true,
      nutritionReference: SampleFoodCatalog.reference,
      allergens: RecipeSuitability.allergensOf(draft).toList()..sort(),
    );
  }
}

